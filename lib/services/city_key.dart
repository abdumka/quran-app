/// The city search key, the same as the server's (C:/Down/Cities/pipeline/
/// citykey.py named the online city files with it, so the two must agree
/// letter for letter; test/city_key_test.dart checks 700+ names).
///
/// Hamza forms, ة/ه, ى/ي, Persian ی/ک, harakat, tatweel, Latin accents,
/// case, a leading Arabic «ال» and a standalone Latin article (al, el, as…)
/// do not matter. Words are joined without spaces.
class CityKey {
  CityKey._();

  // Python decomposes (NFD) and drops the marks; Dart has no NFD, so the
  // letters that decompose to one base letter are listed here (generated by
  // gen_dart_citykey.py: Latin-1, Latin Extended A/B and Additional, Arabic).
