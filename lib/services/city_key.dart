  static final Map<int, int> _fold = () {
    final from = _foldFrom.runes.toList();
    final to = _foldTo.runes.toList();
    return {for (var i = 0; i < from.length; i++) from[i]: to[i]};
  }();

  static final RegExp _marks = RegExp(
    '[\u0300-\u036f\u064b-\u065f\u0670\u0640]',
  );
  static final RegExp _split = RegExp(r"[\s\-'’‘ʼʿʾ`.,()]+");
  static const Map<String, String> _map = {
    'ة': 'ه',
    'ى': 'ي',
    'ٱ': 'ا',
    'ی': 'ي',
    'ک': 'ك',
  };
  static const Set<String> _articles = {
    'al', 'el', 'ad', 'ar', 'as', 'at', 'az', 'ash', 'an', 'adh', 'ath', //
    'aḑ', 'aş', 'aţ', 'az̧',
  };
  static final RegExp _arabicStart = RegExp('^[ء-ي]');

  /// The words of [s] as the search sees them.
  static List<String> words(String s) {
    final folded = StringBuffer();
    for (final r in s.runes) {
      folded.writeCharCode(_fold[r] ?? r);
    }
    var t = folded.toString().replaceAll(_marks, '').toLowerCase();
    _map.forEach((a, b) => t = t.replaceAll(a, b));
    final out = <String>[];
    for (var w in t.split(_split)) {
      if (w.isEmpty || _articles.contains(w)) continue;
      if (_arabicStart.hasMatch(w) && w.startsWith('ال') && w.length >= 4) {
        w = w.substring(2);
      }
      out.add(w);
    }
    return out;
  }

  static String key(String s) => words(s).join();

  /// The online file for a prefix: its letters as hex code points.
  static String prefixFile(String prefix) => prefix.runes
      .map((r) => r.toRadixString(16).padLeft(4, '0'))
      .join('-');
}
