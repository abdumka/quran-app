"""Writes lib/data/recitation_end_caps.dart from tools/recitation_end_caps.json.

Where a recording goes on past the ayah into «صدق الله العظيم», the app stops
before it (owner, 2026-11-20). The JSON keeps the evidence for each cut: the
end of the ayah's last word and the start of the phrase (seconds into the
file), found by the audit in C:/Down/SadaqaAudit (MMS forced alignment, then
Whisper large-v3-turbo on the file's tail). The cut is 0.35 s after the last
word, so its final sound is not clipped, and at least 0.2 s before the phrase.

usage: python tools/build_recitation_end_caps.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'tools', 'recitation_end_caps.json')
OUT = os.path.join(ROOT, 'lib', 'data', 'recitation_end_caps.dart')

data = json.load(open(SRC, encoding='utf-8'))
caps = {}
for e in data['cuts']:
    last, phrase = e['last_word_end_s'], e['phrase_start_s']
    cut = round(min(last + 0.35, phrase - 0.2), 2)
    assert last < cut < phrase, e
    caps.setdefault(e['reciter'], {})[e['file']] = cut

lines = [
    '// GENERATED by tools/build_recitation_end_caps.py from',
    '// tools/recitation_end_caps.json; do not edit by hand.',
    '',
    '/// Where some recordings must stop: after the last ayah of a surah (or a',
    '/// recording session) a few reciters go on to say «صدق الله العظيم», which',
    '/// the app must never play (owner, 2026-11-20: الدوكالي did, after the',
    '/// Quls in the athkar).',
    '///',
    '/// reciter id -> file name -> seconds into that file: nothing in it is',
    '/// played past that point. A per-ayah file becomes a clip ending there; a',
    '/// timed reciter\'s surah file has its spans cut back to it.',
    'const Map<String, Map<String, double>> recitationEndCaps = {',
]
for reciter in sorted(caps):
    lines.append(f"  '{reciter}': {{")
    for f in sorted(caps[reciter]):
        lines.append(f"    '{f}': {caps[reciter][f]},")
    lines.append('  },')
lines.append('};')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(OUT, sum(len(v) for v in caps.values()), 'cuts')
